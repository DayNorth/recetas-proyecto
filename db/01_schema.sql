CREATE TABLE recetas (
    receta_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        INTEGER  NOT NULL,                -- autor
    categoria_id      SMALLINT NOT NULL,
    dificultad_id     SMALLINT NOT NULL,
    titulo            VARCHAR(120) NOT NULL,
    descripcion       TEXT,
    tiempo_prep_min   SMALLINT NOT NULL,
    porciones_base    SMALLINT NOT NULL DEFAULT 1,      -- base para recalcular porciones
    origen            VARCHAR(10) NOT NULL DEFAULT 'LOCAL',
    api_referencia_id VARCHAR(50) NULL,                 -- id en TheMealDB si viene de la API
    estado            VARCHAR(10) NOT NULL DEFAULT 'PUBLICADA',  -- autor "elimina" = INACTIVA; admin retira = MODERADA
