-- Resumen por receta: base para el dashboard
CREATE OR REPLACE VIEW vw_resumen_recetas AS
SELECT r.receta_id,
       r.titulo,
       c.nombre AS categoria,
       CONCAT(u.nombre, ' ', u.apellidos) AS autor,
       (SELECT COUNT(*) FROM visitas_receta v WHERE v.receta_id = r.receta_id) AS total_visitas,
       (SELECT COUNT(*) FROM me_gusta m       WHERE m.receta_id = r.receta_id) AS total_me_gusta,
       (SELECT COUNT(*) FROM favoritos f      WHERE f.receta_id = r.receta_id) AS total_favoritos,
       (SELECT COUNT(*) FROM compartidos s    WHERE s.receta_id = r.receta_id) AS total_compartidos,
       (SELECT ROUND(AVG(calificacion),2) FROM comentarios co WHERE co.receta_id = r.receta_id) AS calificacion_promedio
FROM recetas r
JOIN categorias c ON c.categoria_id = r.categoria_id
JOIN usuarios  u ON u.usuario_id   = r.usuario_id
WHERE r.estado = 'PUBLICADA';

-- Términos más buscados (histórico)
CREATE OR REPLACE VIEW vw_terminos_mas_buscados AS
SELECT LOWER(TRIM(termino)) AS termino,
       COUNT(*)              AS veces_buscado,
       ROUND(AVG(cantidad_resultados),1) AS promedio_resultados
FROM busquedas
GROUP BY LOWER(TRIM(termino))
ORDER BY veces_buscado DESC;

-- Ingredientes más utilizados en recetas
CREATE OR REPLACE VIEW vw_ingredientes_mas_usados AS
SELECT i.nombre AS ingrediente, COUNT(*) AS cantidad_recetas
FROM receta_ingredientes ri
JOIN ingredientes i ON i.ingrediente_id = ri.ingrediente_id
GROUP BY i.nombre
ORDER BY cantidad_recetas DESC;

-- Denuncias de contenido pendientes de revisión (cola del administrador, RF-20)
CREATE OR REPLACE VIEW vw_reportes_contenido_pendientes AS
SELECT rc.reporte_contenido_id,
       rc.fecha,
       rc.motivo,
       rc.descripcion,
       CASE WHEN rc.receta_id IS NOT NULL THEN 'RECETA' ELSE 'COMENTARIO' END AS tipo_contenido,
       COALESCE(r.titulo::text, LEFT(c.comentario, 80), '(solo calificación)') AS contenido,
       CONCAT(u.nombre, ' ', u.apellidos) AS reportado_por
FROM reportes_contenido rc
JOIN usuarios u         ON u.usuario_id = rc.usuario_id
LEFT JOIN recetas r     ON r.receta_id = rc.receta_id
LEFT JOIN comentarios c ON c.comentario_id = rc.comentario_id
WHERE rc.estado = 'PENDIENTE'
ORDER BY rc.fecha;

