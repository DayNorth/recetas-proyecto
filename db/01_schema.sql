-- 7.1 Recetas más vistas en un rango
CREATE FUNCTION sp_reporte_mas_vistas(p_inicio DATE, p_fin DATE, p_limite INT)
RETURNS TABLE (receta_id INT, titulo VARCHAR, categoria VARCHAR, visitas BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT r.receta_id, r.titulo, c.nombre, COUNT(v.visita_id)
    FROM visitas_receta v
    JOIN recetas r    ON r.receta_id = v.receta_id
    JOIN categorias c ON c.categoria_id = r.categoria_id
    WHERE v.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
      AND v.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
    GROUP BY r.receta_id, r.titulo, c.nombre
    ORDER BY 4 DESC, 2
    LIMIT p_limite;
$$;

-- 7.2 Recetas con más "me gusta" en un rango
CREATE FUNCTION sp_reporte_mas_gustadas(p_inicio DATE, p_fin DATE, p_limite INT)
RETURNS TABLE (receta_id INT, titulo VARCHAR, categoria VARCHAR, me_gusta BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT r.receta_id, r.titulo, c.nombre, COUNT(*)
    FROM me_gusta m
    JOIN recetas r    ON r.receta_id = m.receta_id
    JOIN categorias c ON c.categoria_id = r.categoria_id
    WHERE m.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
      AND m.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
    GROUP BY r.receta_id, r.titulo, c.nombre
    ORDER BY 4 DESC, 2
    LIMIT p_limite;
$$;

-- 7.3 Términos más buscados en un rango
CREATE FUNCTION sp_reporte_mas_buscadas(p_inicio DATE, p_fin DATE, p_limite INT)
RETURNS TABLE (termino TEXT, veces_buscado BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT LOWER(TRIM(b.termino)), COUNT(*)
    FROM busquedas b
    WHERE b.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
      AND b.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
    GROUP BY LOWER(TRIM(b.termino))
    ORDER BY 2 DESC, 1
    LIMIT p_limite;
$$;

-- 7.4 Recetas mejor calificadas (mínimo de votos para evitar sesgo)
CREATE FUNCTION sp_reporte_mejor_calificadas(p_inicio DATE, p_fin DATE, p_min_votos INT)
RETURNS TABLE (receta_id INT, titulo VARCHAR, promedio NUMERIC, votos BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT r.receta_id, r.titulo, ROUND(AVG(co.calificacion),2), COUNT(co.calificacion)
    FROM comentarios co
    JOIN recetas r ON r.receta_id = co.receta_id
    WHERE co.calificacion IS NOT NULL
      AND co.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
      AND co.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
    GROUP BY r.receta_id, r.titulo
    HAVING COUNT(co.calificacion) >= p_min_votos
    ORDER BY 3 DESC, 4 DESC;
$$;

-- 7.5 Desempeño por categoría (toma de decisiones: qué contenido crear)
CREATE FUNCTION sp_reporte_por_categoria(p_inicio DATE, p_fin DATE)
RETURNS TABLE (categoria VARCHAR, recetas_publicadas BIGINT, visitas BIGINT, me_gusta BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT c.nombre,
           (SELECT COUNT(*) FROM recetas r2 WHERE r2.categoria_id = c.categoria_id
                                              AND r2.estado = 'PUBLICADA'),
           (SELECT COUNT(*) FROM visitas_receta v JOIN recetas r ON r.receta_id = v.receta_id
             WHERE r.categoria_id = c.categoria_id
               AND v.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
               AND v.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'),
           (SELECT COUNT(*) FROM me_gusta m JOIN recetas r ON r.receta_id = m.receta_id
             WHERE r.categoria_id = c.categoria_id
               AND m.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
               AND m.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica')
    FROM categorias c
    WHERE c.activo = TRUE
    ORDER BY 3 DESC, 1;
$$;

-- 7.6 Tendencia mensual de actividad (gráfico de línea por mes).
--     Incluye los meses sin actividad (en cero) para que el gráfico no salte.
CREATE FUNCTION sp_reporte_tendencia_mensual(p_inicio DATE, p_fin DATE)
RETURNS TABLE (periodo TEXT, visitas BIGINT, me_gusta BIGINT, favoritos BIGINT,
               comentarios BIGINT, compartidos BIGINT, busquedas BIGINT)
LANGUAGE sql STABLE AS $$
    WITH meses AS (
        SELECT g::date AS mes
        FROM generate_series(date_trunc('month', p_inicio::timestamp),
                             date_trunc('month', p_fin::timestamp),
                             interval '1 month') g
    ),
    ev AS (
        SELECT date_trunc('month', fecha AT TIME ZONE 'America/Costa_Rica')::date AS mes, 'v' AS t
          FROM visitas_receta
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
        UNION ALL
        SELECT date_trunc('month', fecha AT TIME ZONE 'America/Costa_Rica')::date, 'l'
          FROM me_gusta
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
        UNION ALL
        SELECT date_trunc('month', fecha AT TIME ZONE 'America/Costa_Rica')::date, 'f'
          FROM favoritos
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
        UNION ALL
        SELECT date_trunc('month', fecha AT TIME ZONE 'America/Costa_Rica')::date, 'c'
          FROM comentarios
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
        UNION ALL
        SELECT date_trunc('month', fecha AT TIME ZONE 'America/Costa_Rica')::date, 's'
          FROM compartidos
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
        UNION ALL
        SELECT date_trunc('month', fecha AT TIME ZONE 'America/Costa_Rica')::date, 'b'
          FROM busquedas
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
    )
    SELECT TO_CHAR(m.mes, 'YYYY-MM'),
           COUNT(*) FILTER (WHERE ev.t = 'v'),
           COUNT(*) FILTER (WHERE ev.t = 'l'),
           COUNT(*) FILTER (WHERE ev.t = 'f'),
           COUNT(*) FILTER (WHERE ev.t = 'c'),
           COUNT(*) FILTER (WHERE ev.t = 's'),
           COUNT(*) FILTER (WHERE ev.t = 'b')
    FROM meses m
    LEFT JOIN ev ON ev.mes = m.mes
    GROUP BY m.mes
    ORDER BY m.mes;
$$;

-- 7.7 Búsquedas sin resultados (demanda insatisfecha: qué recetas agregar)
CREATE FUNCTION sp_reporte_busquedas_sin_resultado(p_inicio DATE, p_fin DATE, p_limite INT)
RETURNS TABLE (termino TEXT, veces_buscado BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT LOWER(TRIM(b.termino)), COUNT(*)
    FROM busquedas b
    WHERE b.cantidad_resultados = 0
      AND b.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
      AND b.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
    GROUP BY LOWER(TRIM(b.termino))
    ORDER BY 2 DESC, 1
    LIMIT p_limite;
$$;

-- 7.8 Recalcular ingredientes según porciones deseadas (cálculo matemático).
--     Devuelve también los IDs; las unidades no escalables ("al gusto")
--     conservan su cantidad.
CREATE FUNCTION sp_ingredientes_por_porciones(p_receta_id INT, p_porciones INT)
RETURNS TABLE (ingrediente VARCHAR, cantidad NUMERIC, unidad VARCHAR, nota VARCHAR,
               ingrediente_id INT, unidad_id SMALLINT)
LANGUAGE sql STABLE AS $$
    SELECT i.nombre,
           CASE WHEN um.escalable
                THEN ROUND(ri.cantidad * p_porciones / r.porciones_base, 2)
                ELSE ri.cantidad END,
           um.abreviatura,
           ri.nota,
           ri.ingrediente_id,
           ri.unidad_id
    FROM receta_ingredientes ri
    JOIN recetas r          ON r.receta_id = ri.receta_id
    JOIN ingredientes i     ON i.ingrediente_id = ri.ingrediente_id
    JOIN unidades_medida um ON um.unidad_id = ri.unidad_id
    WHERE ri.receta_id = p_receta_id
      AND p_porciones > 0
    ORDER BY i.nombre;
$$;

-- 7.9 Recetas más buscadas: visitas que se originaron en una búsqueda.
--     (cuenta recetas abiertas desde los resultados, no todas las que aparecieron)
CREATE FUNCTION sp_reporte_recetas_mas_buscadas(p_inicio DATE, p_fin DATE, p_limite INT)
RETURNS TABLE (receta_id INT, titulo VARCHAR, categoria VARCHAR,
               visitas_desde_busqueda BIGINT, terminos_distintos BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT r.receta_id, r.titulo, c.nombre,
           COUNT(v.visita_id),
           COUNT(DISTINCT LOWER(TRIM(b.termino)))
    FROM visitas_receta v
    JOIN busquedas b  ON b.busqueda_id = v.busqueda_id
    JOIN recetas r    ON r.receta_id = v.receta_id
    JOIN categorias c ON c.categoria_id = r.categoria_id
    WHERE v.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
      AND v.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
    GROUP BY r.receta_id, r.titulo, c.nombre
    ORDER BY 4 DESC, 5 DESC, 2
    LIMIT p_limite;
$$;

-- 7.10 Conversión: de cada 100 visitas, cuántas terminan en una interacción (me gusta,
--      compartido o señal anónima de interacciones_receta). Toma de decisiones: recetas
--      que atraen pero no convencen. Ordenado de menor a mayor tasa.
CREATE FUNCTION sp_reporte_conversion(p_inicio DATE, p_fin DATE, p_min_visitas INT)
RETURNS TABLE (receta_id INT, titulo VARCHAR, categoria VARCHAR, visitas BIGINT,
               me_gusta BIGINT, interacciones BIGINT, tasa_conversion NUMERIC, calificacion_promedio NUMERIC)
LANGUAGE sql STABLE AS $$
    WITH v AS (
        SELECT receta_id, COUNT(*) AS n FROM visitas_receta
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
         GROUP BY receta_id
    ), l AS (
        SELECT receta_id, COUNT(*) AS n FROM me_gusta
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
         GROUP BY receta_id
    ), o AS (
        SELECT receta_id, COUNT(*) AS n FROM (
            SELECT receta_id, fecha FROM compartidos
            UNION ALL
            SELECT receta_id, fecha FROM interacciones_receta
        ) x
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
         GROUP BY receta_id
    ), q AS (
        SELECT receta_id, ROUND(AVG(calificacion),2) AS prom FROM comentarios
         WHERE fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
           AND fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica'
         GROUP BY receta_id
    )
    SELECT r.receta_id, r.titulo, c.nombre, v.n, COALESCE(l.n, 0),
           COALESCE(l.n, 0) + COALESCE(o.n, 0),
           ROUND((COALESCE(l.n, 0) + COALESCE(o.n, 0)) * 100.0 / v.n, 2), q.prom
    FROM v
    JOIN recetas r    ON r.receta_id = v.receta_id
    JOIN categorias c ON c.categoria_id = r.categoria_id
    LEFT JOIN l ON l.receta_id = v.receta_id
    LEFT JOIN o ON o.receta_id = v.receta_id
    LEFT JOIN q ON q.receta_id = v.receta_id
    WHERE v.n >= p_min_visitas
    ORDER BY 7 ASC, 4 DESC;
$$;

-- 7.11 Oferta vs. demanda por categoría (toma de decisiones: dónde crear
--      más recetas). visitas_por_receta alto = mucha demanda para poca oferta.
--      Sin recetas publicadas pero con demanda, la razón es NULL y sale primero.
CREATE FUNCTION sp_reporte_oferta_demanda_categoria(p_inicio DATE, p_fin DATE)
RETURNS TABLE (categoria VARCHAR, recetas_publicadas BIGINT, visitas BIGINT,
               visitas_por_receta NUMERIC, busquedas BIGINT, busquedas_sin_resultado BIGINT)
LANGUAGE sql STABLE AS $$
    WITH base AS (
        SELECT c.nombre,
               (SELECT COUNT(*) FROM recetas r
                 WHERE r.categoria_id = c.categoria_id AND r.estado = 'PUBLICADA') AS recetas,
               (SELECT COUNT(*) FROM visitas_receta v JOIN recetas r ON r.receta_id = v.receta_id
                 WHERE r.categoria_id = c.categoria_id
                   AND v.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
                   AND v.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica') AS visitas,
               (SELECT COUNT(*) FROM busquedas b
                 WHERE b.categoria_id = c.categoria_id
                   AND b.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
                   AND b.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica') AS busq,
               (SELECT COUNT(*) FROM busquedas b
                 WHERE b.categoria_id = c.categoria_id AND b.cantidad_resultados = 0
                   AND b.fecha >= p_inicio::timestamp AT TIME ZONE 'America/Costa_Rica'
                   AND b.fecha <  (p_fin + 1)::timestamp AT TIME ZONE 'America/Costa_Rica') AS busq0
        FROM categorias c
        WHERE c.activo = TRUE
    )
    SELECT nombre, recetas, visitas,
           ROUND(visitas::numeric / NULLIF(recetas, 0), 2),
           busq, busq0
    FROM base
    ORDER BY 4 DESC NULLS FIRST, 1;
$$;

