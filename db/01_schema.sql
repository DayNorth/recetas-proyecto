-- Denuncia de un usuario sobre una receta O un comentario
CREATE TABLE reportes_contenido (
    reporte_contenido_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     INTEGER NOT NULL,                   -- quien reporta
    receta_id      INTEGER NULL,                       -- exactamente uno de los dos
    comentario_id  INTEGER NULL,
    motivo         VARCHAR(20) NOT NULL,
    descripcion    VARCHAR(500),                       -- detalle opcional
    estado         VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE',
    resolucion     VARCHAR(500),                       -- explicación del administrador
    atendido_por   INTEGER NULL,
    fecha          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_atencion TIMESTAMPTZ NULL,
    CONSTRAINT fk_rc_usuario    FOREIGN KEY (usuario_id)    REFERENCES usuarios(usuario_id),
    CONSTRAINT fk_rc_receta     FOREIGN KEY (receta_id)     REFERENCES recetas(receta_id)       ON DELETE CASCADE,
    CONSTRAINT fk_rc_comentario FOREIGN KEY (comentario_id) REFERENCES comentarios(comentario_id) ON DELETE CASCADE,
    CONSTRAINT fk_rc_atendido   FOREIGN KEY (atendido_por)  REFERENCES usuarios(usuario_id),
    CONSTRAINT chk_rc_objetivo  CHECK ((receta_id IS NOT NULL)::int + (comentario_id IS NOT NULL)::int = 1),
    CONSTRAINT chk_rc_motivo    CHECK (motivo IN ('SPAM','OFENSIVO','INCORRECTO','DERECHOS_AUTOR','OTRO')),
    CONSTRAINT chk_rc_estado    CHECK (estado IN ('PENDIENTE','MANTENIDO','MODERADO')),
    CONSTRAINT chk_rc_atencion  CHECK (
        (estado = 'PENDIENTE' AND atendido_por IS NULL AND fecha_atencion IS NULL) OR
        (estado <> 'PENDIENTE' AND atendido_por IS NOT NULL AND fecha_atencion IS NOT NULL))
);
-- Un usuario no puede tener dos denuncias pendientes sobre el mismo contenido
CREATE UNIQUE INDEX uq_rc_pendiente_receta ON reportes_contenido(usuario_id, receta_id)
    WHERE estado = 'PENDIENTE' AND receta_id IS NOT NULL;
CREATE UNIQUE INDEX uq_rc_pendiente_comentario ON reportes_contenido(usuario_id, comentario_id)
    WHERE estado = 'PENDIENTE' AND comentario_id IS NOT NULL;
CREATE INDEX idx_rc_estado     ON reportes_contenido(estado, fecha);
CREATE INDEX idx_rc_receta     ON reportes_contenido(receta_id)     WHERE receta_id IS NOT NULL;
CREATE INDEX idx_rc_comentario ON reportes_contenido(comentario_id) WHERE comentario_id IS NOT NULL;

