    fecha_actualizacion TIMESTAMPTZ NULL,               -- se actualiza con trigger
    CONSTRAINT fk_recetas_usuario    FOREIGN KEY (usuario_id)    REFERENCES usuarios(usuario_id),
    CONSTRAINT fk_recetas_categoria  FOREIGN KEY (categoria_id)  REFERENCES categorias(categoria_id),
    CONSTRAINT fk_recetas_dificultad FOREIGN KEY (dificultad_id) REFERENCES niveles_dificultad(dificultad_id),
    CONSTRAINT chk_recetas_tiempo    CHECK (tiempo_prep_min > 0),
    CONSTRAINT chk_recetas_porciones CHECK (porciones_base > 0),
    CONSTRAINT chk_recetas_origen    CHECK (origen IN ('LOCAL','API')),
    CONSTRAINT chk_recetas_estado    CHECK (estado IN ('BORRADOR','PUBLICADA','INACTIVA','MODERADA')),
    CONSTRAINT uq_recetas_api UNIQUE (api_referencia_id)
);

-- Reemplaza ON UPDATE CURRENT_TIMESTAMP de MySQL
CREATE FUNCTION fn_set_fecha_actualizacion() RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_recetas_fecha_actualizacion
    BEFORE UPDATE ON recetas
    FOR EACH ROW EXECUTE FUNCTION fn_set_fecha_actualizacion();

