--    Se llaman desde la API (ASP.NET Core / EF Core, SQL directo) con:  SELECT * FROM sp_reporte_...(...)
--    y el resultado se exporta a PDF/CSV/XLSX.
--
--    Rango por mes: p_inicio y p_fin son fechas de Costa Rica. El rango
--    cubre desde las 00:00 de p_inicio hasta las 24:00 de p_fin
--    (hora 'America/Costa_Rica'), sin usar BETWEEN, así no se pierde el
--    último día y se aprovechan los índices por fecha.
--    Escritas en LANGUAGE sql: ORDER BY usa la posición de la columna.
